using System.Globalization;
using System.Linq;
using System.Text;

namespace TiaSbom.Core
{
    /// <summary>README.md for a project repository — regenerated on every export.</summary>
    public static class Readme
    {
        public static string Build(string key, ProjectSnapshot s)
        {
            int modules = s.Items.Count(i => i.IsProduct);
            var sb = new StringBuilder();
            sb.AppendLine($"# SBOM – {key}");
            sb.AppendLine();
            sb.AppendLine("Generated by TiaSbom. Do not edit by hand.");
            sb.AppendLine();
            sb.AppendLine("| | |");
            sb.AppendLine("|---|---|");
            sb.AppendLine($"| Project key (TIA *Family*) | `{key}` |");
            sb.AppendLine($"| Last exported project | `{s.ProjectName}` |");
            sb.AppendLine($"| TIA Portal | {s.TiaVersion} |");
            sb.AppendLine($"| Hardware modules | {modules} |");
            sb.AppendLine($"| Exported | {s.ExportedAtUtc.ToString("yyyy-MM-dd HH:mm 'UTC'", CultureInfo.InvariantCulture)} by {s.ExportedBy} |");
            sb.AppendLine();
            sb.AppendLine("## Files");
            sb.AppendLine();
            sb.AppendLine("- `latest.json` – last exported SBOM (CycloneDX " + SbomBuilder.SpecVersion + ")");
            sb.AppendLine("- `versions/<project name>/sbom.json` – one folder and one git tag per TIA project version");
            return sb.ToString();
        }
    }
}
