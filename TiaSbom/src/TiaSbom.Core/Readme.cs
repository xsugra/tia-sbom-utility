using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace TiaSbom.Core
{
    /// <summary>README.md for a project repository — regenerated on every export.</summary>
    public static class Readme
    {
        /// <param name="versions">Versions already in the repository; the current export replaces its own entry.</param>
        /// <param name="versionName">Name of the current export in the repository, see <see cref="ExportPlan"/>.</param>
        public static string Build(string key, ProjectSnapshot s, IEnumerable<PreviousSbom> versions, string versionName)
        {
            int modules = s.Items.Count(i => i.IsProduct);
            string exported = s.ExportedAtUtc.ToUniversalTime().ToString(SbomBuilder.TimestampFormat, CultureInfo.InvariantCulture);

            // Sorted by Gitea commit time: the clocks of the exporting PCs can differ. The current export has none yet.
            var older = versions
                .Where(v => !string.Equals(v.VersionName, versionName, StringComparison.OrdinalIgnoreCase))
                .OrderByDescending(v => v.StoredAt);
            var rows = new[]
            {
                new PreviousSbom
                {
                    VersionName = versionName,
                    TiaVersion = s.TiaVersion,
                    ModuleCount = modules,
                    ExportedBy = s.ExportedBy,
                    Timestamp = exported,
                },
            }.Concat(older);

            var sb = new StringBuilder();
            sb.AppendLine($"# SBOM – {key}");
            sb.AppendLine();
            sb.AppendLine("Generated by TiaSbom. Do not edit by hand.");
            sb.AppendLine();
            sb.AppendLine($"Project key: `{key}`");
            sb.AppendLine();
            sb.AppendLine("## Versions");
            sb.AppendLine();
            sb.AppendLine("All of these can be in use at the same time.");
            sb.AppendLine();
            sb.AppendLine("| Project version | TIA Portal | Hardware modules | Exported (UTC) | By |");
            sb.AppendLine("|---|---|---|---|---|");
            foreach (PreviousSbom row in rows)
            {
                sb.AppendLine($"| [`{row.VersionName}`](versions/{row.VersionName}/sbom.json) | {row.TiaVersion} | " +
                              $"{row.ModuleCount} | {row.Timestamp} | {row.ExportedBy} |");
            }
            sb.AppendLine();
            sb.AppendLine("## Files");
            sb.AppendLine();
            sb.AppendLine("- `versions/<project name>/sbom.json` – one folder and one git tag per TIA project version (CycloneDX " + SbomBuilder.SpecVersion + ")");
            sb.AppendLine("- `latest.json` – most recently exported version only, not a complete view of the repository");
            return sb.ToString();
        }
    }
}
